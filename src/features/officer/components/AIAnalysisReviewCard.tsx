import React from 'react';
import { AIAnalysisResult } from '../../../types/ai';
import { Sparkles, Info, ShieldAlert, CheckCircle2, AlertTriangle, Bug } from 'lucide-react';
import Badge from '../../../components/ui/Badge';
import Progress from '../../../components/ui/Progress';

interface AIAnalysisReviewCardProps {
  analysis?: AIAnalysisResult | null;
}

export const AIAnalysisReviewCard: React.FC<AIAnalysisReviewCardProps> = ({ analysis }) => {
  if (!analysis) {
    return (
      <div className="p-5 rounded-card bg-neutral-50 border border-neutral-200 text-xs text-neutral-500 space-y-2">
        <div className="flex items-center gap-2">
          <Sparkles className="w-4 h-4 text-neutral-400" />
          <h3 className="font-bold text-neutral-700">AI Diagnostic Inference</h3>
        </div>
        <p>No computer vision analysis has been recorded for this case report yet.</p>
      </div>
    );
  }

  const pred = analysis.prediction;
  const confidence = pred?.confidence;
  const percent = confidence !== undefined ? Math.round(confidence > 1 ? confidence : confidence * 100) : null;

  const getCategoryConfig = (cat?: string) => {
    switch (cat) {
      case 'pest':
        return { label: 'Insect Pest Infestation', variant: 'warning' as const, icon: <Bug className="w-3.5 h-3.5" /> };
      case 'healthy':
        return { label: 'Healthy Crop', variant: 'success' as const, icon: <CheckCircle2 className="w-3.5 h-3.5" /> };
      case 'disease':
      default:
        return { label: 'Pathogenic Disease', variant: 'error' as const, icon: <Sparkles className="w-3.5 h-3.5" /> };
    }
  };

  const catConfig = getCategoryConfig(pred?.category);

  return (
    <section
      aria-label="Computer Vision & AI Inference Findings"
      className="p-5 sm:p-6 rounded-card bg-emerald-50/40 border-2 border-emerald-300/80 shadow-xs space-y-4"
    >
      {/* Prominent Distinction Notice */}
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-emerald-200/80 pb-3">
        <div className="flex items-center gap-2">
          <div className="w-8 h-8 rounded-full bg-emerald-100 text-primary flex items-center justify-center shrink-0">
            <Sparkles className="w-4 h-4 text-primary" aria-hidden="true" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h3 className="text-base font-bold text-neutral-900 tracking-tight">
                AI Diagnostic Assessment (Advisory Model)
              </h3>
              <Badge variant="info" size="sm" className="text-[11px] font-bold">
                Automated Reference
              </Badge>
            </div>
            <p className="text-xs text-neutral-600 font-sans">
              Generated by Groq vision engine. Advisory reference only — subject to agronomist review.
            </p>
          </div>
        </div>

        <Badge variant={catConfig.variant} size="md" className="gap-1.5 font-semibold text-xs">
          {catConfig.icon}
          <span>{catConfig.label}</span>
        </Badge>
      </div>

      {/* Advisory Banner for Officer */}
      <div className="p-3 bg-white rounded-lg border border-emerald-200 text-xs text-neutral-700 flex items-start gap-2 shadow-2xs">
        <Info className="w-4 h-4 text-primary shrink-0 mt-0.5" aria-hidden="true" />
        <p className="leading-relaxed">
          <strong className="text-neutral-900 font-semibold">Agronomist Validation Rule: </strong>
          High model confidence is not an automatic verification. As Agricultural Officer, your professional field corroboration takes precedence over AI inference output.
        </p>
      </div>

      {/* Prediction Details */}
      <div className="p-4 rounded-lg bg-white border border-emerald-200/90 shadow-2xs space-y-3">
        <div>
          <span className="text-[11px] font-bold uppercase tracking-wider text-neutral-500 block">
            Identified Pathogen / Pest
          </span>
          <h4 className="text-lg font-bold text-neutral-900 leading-snug">
            {pred?.label || 'Condition Identified'}
          </h4>
          {pred?.scientificName && (
            <span className="text-xs italic text-neutral-600 block mt-0.5 font-sans">
              Scientific binomial: {pred.scientificName}
            </span>
          )}
        </div>

        {/* Confidence & Severity Grid */}
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-1 border-t border-neutral-100">
          <div className="p-3 bg-neutral-50 rounded-lg space-y-1.5">
            <div className="flex items-center justify-between text-xs">
              <span className="font-bold text-neutral-700">Model Confidence</span>
              <span className="font-mono font-bold text-neutral-900">
                {percent !== null ? `${percent}%` : 'Not available'}
              </span>
            </div>
            {percent !== null ? (
              <Progress value={percent} variant="ai" size="sm" aria-label={`Confidence: ${percent}%`} />
            ) : (
              <span className="text-xs text-neutral-400 italic">Confidence not available</span>
            )}
          </div>

          <div className="p-3 bg-neutral-50 rounded-lg flex items-center justify-between">
            <div className="space-y-0.5">
              <span className="font-bold text-neutral-700 text-xs block">Assessed Severity</span>
              <span className="text-[11px] text-neutral-500 block">By model indicators</span>
            </div>
            <span className="font-bold text-xs uppercase px-2.5 py-1 rounded bg-neutral-200 text-neutral-800">
              {analysis.severity || 'Unknown'}
            </span>
          </div>
        </div>

        {/* Explanation */}
        {analysis.explanation && (
          <div className="pt-2 border-t border-neutral-100">
            <span className="text-[11px] font-bold uppercase tracking-wider text-neutral-600 block mb-1">
              AI Pathology Rationale
            </span>
            <p className="text-xs text-neutral-700 leading-relaxed font-sans">
              {analysis.explanation}
            </p>
          </div>
        )}
      </div>

      {/* Symptoms & Causes split */}
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
        {analysis.observedSymptoms && analysis.observedSymptoms.length > 0 && (
          <div className="p-3.5 bg-white rounded-lg border border-emerald-200/90 space-y-1.5 shadow-2xs">
            <span className="font-bold text-neutral-800 uppercase text-[11px] block">
              Observed Symptoms Checklist
            </span>
            <ul className="space-y-1 text-neutral-700">
              {analysis.observedSymptoms.map((s, idx) => (
                <li key={idx} className="flex items-start gap-1.5">
                  <span className="w-1.5 h-1.5 rounded-full bg-primary mt-1.5 shrink-0" />
                  <span>{s}</span>
                </li>
              ))}
            </ul>
          </div>
        )}

        {analysis.recommendations && analysis.recommendations.length > 0 && (
          <div className="p-3.5 bg-white rounded-lg border border-emerald-200/90 space-y-1.5 shadow-2xs">
            <span className="font-bold text-neutral-800 uppercase text-[11px] block">
              AI Suggested Cultural Actions
            </span>
            <ul className="space-y-1 text-neutral-700">
              {analysis.recommendations.map((r, idx) => (
                <li key={idx} className="flex items-start gap-1.5">
                  <CheckCircle2 className="w-3.5 h-3.5 text-primary shrink-0 mt-0.5" />
                  <span>{r}</span>
                </li>
              ))}
            </ul>
          </div>
        )}
      </div>

      {/* Warnings & Escalation Flag */}
      {analysis.requiresOfficerEscalation && (
        <div className="p-3 bg-rose-50 rounded-lg border border-rose-200 text-rose-900 text-xs flex items-start gap-2">
          <ShieldAlert className="w-4 h-4 text-rose-600 shrink-0 mt-0.5" />
          <div>
            <strong className="font-bold">Automated Officer Escalation Triggered: </strong>
            <span>{analysis.escalationReason || 'Pathogen density requires block agronomist signoff.'}</span>
          </div>
        </div>
      )}

      {analysis.warnings && analysis.warnings.length > 0 && (
        <div className="p-3 bg-amber-50 rounded-lg border border-amber-200 text-amber-900 text-xs flex items-start gap-2">
          <AlertTriangle className="w-4 h-4 text-amber-600 shrink-0 mt-0.5" />
          <div>
            <strong className="font-bold">Agronomic Caution: </strong>
            <span>{analysis.warnings.join(' • ')}</span>
          </div>
        </div>
      )}
    </section>
  );
};

export default AIAnalysisReviewCard;
